def main():
    """Main entry point"""
    results_dir = sys.argv[1] if len(sys.argv) > 1 else "simulation_results"
    output_dir = sys.argv[2] if len(sys.argv) > 2 else "generated_code"
    
    # Load insights
    insights_file = Path(results_dir) / "simulation_insights.json"
    if not insights_file.exists():
        print(f"Error: No insights found at {insights_file}")
        print("Run python3 run_revolution.py first")
        sys.exit(1)
    
    with open(insights_file) as f:
        insights = json.load(f)
    
    # Generate code
    pipeline = CodeGenerationPipeline(insights, output_dir)
    pipeline.generate_all()


if __name__ == "__main__":
    main()
