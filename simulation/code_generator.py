class CodeGenerationPipeline:
    """Complete code generation pipeline"""
    
    def __init__(self, insights: Dict, output_dir: str):
        self.insights = insights
        self.output_dir = Path(output_dir)
        self.kernel_gen = KernelCodeGenerator(insights)
        self.test_gen = TestGenerator(insights)
    
    def generate_all(self):
        """Generate all code"""
        print("\n" + "=" * 80)
        print("CUDA Open - Automatic Code Generation".center(80))
        print("=" * 80 + "\n")
        
        # Create output directory
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
        # Generate kernels
        files_generated = []
        
        print("Generating optimized kernels...\n")
        
        # 1. BitNet GEMM
        bitnet_code = self.kernel_gen.generate_bitnet_gemm()
        bitnet_file = self.output_dir / "bitnet_gemm_auto_generated.h"
        with open(bitnet_file, 'w') as f:
            f.write(bitnet_code)
        files_generated.append(bitnet_file)
        print(f"  ✓ {bitnet_file.name}")
        
        # 2. Adaptive Tiling
        tiling_code = self.kernel_gen.generate_adaptive_tiling()
        tiling_file = self.output_dir / "adaptive_tiling_auto_generated.h"
        with open(tiling_file, 'w') as f:
            f.write(tiling_code)
        files_generated.append(tiling_file)
        print(f"  ✓ {tiling_file.name}")
        
        # 3. Multi-Precision Fusion
        fusion_code = self.kernel_gen.generate_multi_precision_fusion()
        fusion_file = self.output_dir / "multi_precision_fusion_auto_generated.h"
        with open(fusion_file, 'w') as f:
            f.write(fusion_code)
        files_generated.append(fusion_file)
        print(f"  ✓ {fusion_file.name}")
        
        # 4. Benchmark tests
        test_code = self.test_gen.generate_benchmark_tests()
        test_file = self.output_dir / "test_generated_kernels.cpp"
        with open(test_file, 'w') as f:
            f.write(test_code)
        files_generated.append(test_file)
        print(f"  ✓ {test_file.name}")
        
        # Summary
        print(f"\n✓ Generated {len(files_generated)} files")
        print(f"  Location: {self.output_dir}")
        print("\nNext steps:")
        print("  1. Review generated code")
        print("  2. Integrate into C++ framework")
        print("  3. Run benchmarks")
        print("  4. Compare with baseline implementations")
        print("\n" + "=" * 80)


